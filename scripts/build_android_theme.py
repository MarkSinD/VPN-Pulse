"""Turn the Mini App's design tokens into Android resources.

`web/src/ui-tokens.css` is the single source of the v5 "instrument panel" look. The Android probe
must not carry a second copy of the palette, so its colours and metrics are generated from that
file: the `:root` block becomes `values/colors.xml` (light), the `prefers-color-scheme: dark`
block becomes `values-night/colors.xml`, and the spacing, radii, control sizes and type scale
become `values/dimens.xml` (dp for space, sp for text, so system text scaling still works).

Run: python scripts/build_android_theme.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "web" / "src" / "ui-tokens.css"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# the colours the app uses; everything else in the stylesheet is web-only (gradients, shadows)
COLORS = (
    "bg", "surface", "raised", "well", "text", "muted", "accent", "accent-text",
    "border", "border-strong", "operational", "degraded", "unavailable", "unknown", "admin", "focus",
)
DP = {  # token -> resource name
    "space-1": "space_1", "space-2": "space_2", "space-3": "space_3", "space-4": "space_4",
    "space-5": "space_5", "space-6": "space_6", "radius-sm": "radius_sm", "radius-md": "radius_md",
    "radius-lg": "radius_lg", "control-min": "control_min", "row-min": "row_min",
    "accordion-min": "accordion_min", "ring-size": "ring_size", "focus-width": "focus_width",
}
SP = {"text-xs": "text_xs", "text-sm": "text_sm", "text-md": "text_md", "text-lg": "text_lg", "text-xl": "text_xl"}
MS = {"motion-fast": "motion_fast", "motion-normal": "motion_normal"}
REM = 16.0  # the Mini App's rem base; Android scales sp itself


def blocks(css: str) -> tuple[dict[str, str], dict[str, str]]:
    """(light, dark) token maps. Light is the first `:root {`, dark the one inside the media query."""
    light_at = css.index(":root {")
    dark_at = css.index("@media (prefers-color-scheme: dark)")
    light = dict(re.findall(r"--([a-z0-9-]+):\s*([^;]+);", css[light_at:dark_at]))
    dark = dict(re.findall(r"--([a-z0-9-]+):\s*([^;]+);", css[dark_at:]))
    return {k: v.strip() for k, v in light.items()}, {k: v.strip() for k, v in dark.items()}


def to_argb(value: str, tokens: dict[str, str], seen: tuple[str, ...] = ()) -> str | None:
    """#rgb / #rrggbb / rgba(r, g, b, a) / var(--other) -> #AARRGGBB. Anything else: None."""
    value = value.strip()
    reference = re.fullmatch(r"var\(--([a-z0-9-]+)\)", value)
    if reference:
        name = reference.group(1)
        if name in seen or name not in tokens:
            return None
        return to_argb(tokens[name], tokens, seen + (name,))
    if value.startswith("#"):
        digits = value[1:]
        if len(digits) == 3:
            digits = "".join(c * 2 for c in digits)
        if len(digits) == 6:
            return "#FF" + digits.upper()
        if len(digits) == 8:  # css is #rrggbbaa, android is #aarrggbb
            return ("#" + digits[6:8] + digits[0:6]).upper()
        return None
    rgba = re.fullmatch(r"rgba?\(([^)]+)\)", value)
    if rgba:
        parts = [p.strip() for p in rgba.group(1).replace("/", ",").split(",") if p.strip()]
        if len(parts) not in (3, 4):
            return None
        try:
            r, g, b = (max(0, min(255, round(float(p)))) for p in parts[:3])
            a = float(parts[3]) if len(parts) == 4 else 1.0
        except ValueError:
            return None
        return f"#{round(max(0.0, min(1.0, a)) * 255):02X}{r:02X}{g:02X}{b:02X}"
    return None


def px(value: str) -> float | None:
    match = re.fullmatch(r"(-?[\d.]+)\s*(px|rem|ms|s)?", value.strip())
    if not match:
        return None
    number, unit = float(match.group(1)), match.group(2) or "px"
    if unit == "rem":
        return number * REM
    if unit == "s":
        return number * 1000
    return number


def number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else f"{value:g}"


def colors_xml(tokens: dict[str, str], theme: str) -> str:
    lines = [
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>",
        f"<!-- Generated by scripts/build_android_theme.py from web/src/ui-tokens.css ({theme}). Do not edit. -->",
        "<resources>",
    ]
    missing = []
    for name in COLORS:
        argb = to_argb(tokens.get(f"color-{name}", ""), tokens)
        if argb is None:
            missing.append(name)
            continue
        lines.append(f'    <color name="color_{name.replace("-", "_")}">{argb}</color>')
    lines.append("</resources>")
    if missing:
        raise SystemExit(f"build_android_theme: no usable value for {theme} colours: {', '.join(missing)}")
    return "\n".join(lines) + "\n"


def dimens_xml(tokens: dict[str, str]) -> str:
    lines = [
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>",
        "<!-- Generated by scripts/build_android_theme.py from web/src/ui-tokens.css. Do not edit. -->",
        "<resources>",
    ]
    for group, unit, comment in ((DP, "dp", "spacing, radii and control sizes"), (SP, "sp", "type scale — sp so 200 % system text still works"), (MS, "", "motion, in milliseconds")):
        lines.append(f"    <!-- {comment} -->")
        for token, name in group.items():
            value = px(tokens.get(token, ""))
            if value is None:
                raise SystemExit(f"build_android_theme: token --{token} is missing or not a length")
            if unit:
                lines.append(f'    <dimen name="{name}">{number(value)}{unit}</dimen>')
            else:
                lines.append(f'    <integer name="{name}">{number(value)}</integer>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    before = path.read_text(encoding="utf-8") if path.exists() else None
    path.write_text(text, encoding="utf-8", newline="\n")
    return before != text


def main() -> int:
    if not TOKENS.exists():
        print(f"tokens not found: {TOKENS}", file=sys.stderr)
        return 2
    css = TOKENS.read_text(encoding="utf-8")
    light, dark = blocks(css)
    changed = [
        write(RES / "values" / "colors.xml", colors_xml(light, "light")),
        write(RES / "values-night" / "colors.xml", colors_xml({**light, **dark}, "dark")),
        write(RES / "values" / "dimens.xml", dimens_xml(light)),
    ]
    print(f"android theme: {len(COLORS)} colours × 2 themes, {len(DP) + len(SP) + len(MS)} metrics"
          f" → {RES.relative_to(ROOT).as_posix()} ({'updated' if any(changed) else 'unchanged'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
