"""Turn the brand mark into the probe's launcher icon.

`web/brand/logo.svg` is the mark — the pulse line of the app's own icon set, round caps, on a
24-unit grid — and `web/src/ui-tokens.css` holds the colours. The Android icon must not be a
second drawing of either, so it is generated: the same path, placed on the 108-unit grid an
adaptive icon wants, over the dark surface the app uses at night.

What it writes (all under android/app/src/main/res):

  drawable/ic_launcher_foreground.xml   the mark, in --color-operational
  drawable/ic_launcher_monochrome.xml   the same path for Android 13's themed icons, tinted white
  values/ic_launcher.xml                the background colour, from the dark --color-bg
  mipmap-anydpi-v26/ic_launcher.xml     the adaptive icon itself, and its round twin

minSdk is 26, so adaptive icons are all the launchers can ask for: no PNG densities, no raster.

Run: python scripts/build_android_icon.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGO = ROOT / "web" / "brand" / "logo.svg"
TOKENS = ROOT / "web" / "src" / "ui-tokens.css"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# An adaptive icon is drawn on 108 units and masked to the middle: the launcher shows about the
# central 66 and may crop to a circle, so nothing should reach further than 33 from the centre.
# The mark is 18 units wide on its own 24-unit grid; at this scale its ends land 21.6 units out,
# 25 with half the stroke — three quarters of what the mask shows, which leaves it air.
GRID = 108
SCALE = 2.4
# x -> x * SCALE + OFFSET keeps the 24-grid's centre (12, 12) at the icon's centre (54, 54)
OFFSET = GRID / 2 - 12 * SCALE
GENERATED = "Generated by scripts/build_android_icon.py from web/brand/logo.svg. Do not edit."


def mark() -> tuple[str, str]:
    """(the path, the stroke width) of the one shape in the brand mark."""
    svg = LOGO.read_text(encoding="utf-8")
    path = re.search(r'<path[^>]*\sd="([^"]+)"', svg)
    width = re.search(r'stroke-width="([\d.]+)"', svg)
    if not path or not width:
        raise SystemExit(f"{LOGO.name} is not the single stroked path this script knows how to read")
    if svg.count("<path") != 1:
        raise SystemExit(f"{LOGO.name} has more than one path: teach this script how to place them")
    return path.group(1), width.group(1)


def dark_token(name: str) -> str:
    """A colour from the dark block of the stylesheet, as #AARRGGBB."""
    css = TOKENS.read_text(encoding="utf-8")
    dark = css[css.index("@media (prefers-color-scheme: dark)"):]
    found = re.search(rf"--{name}:\s*(#[0-9a-fA-F]{{3,8}})\s*;", dark)
    if not found:
        raise SystemExit(f"--{name} is not a plain colour in the dark block of {TOKENS.name}")
    digits = found.group(1)[1:]
    if len(digits) == 3:
        digits = "".join(c * 2 for c in digits)
    if len(digits) != 6:
        raise SystemExit(f"--{name} is {found.group(1)}, which this script cannot flatten")
    return "#FF" + digits.upper()


def vector(path: str, stroke: str, colour: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{GRID}dp"
    android:height="{GRID}dp"
    android:viewportWidth="{GRID}"
    android:viewportHeight="{GRID}">
    <group
        android:scaleX="{SCALE:g}"
        android:scaleY="{SCALE:g}"
        android:translateX="{OFFSET:g}"
        android:translateY="{OFFSET:g}">
        <path
            android:pathData="{path}"
            android:strokeColor="{colour}"
            android:strokeWidth="{stroke}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
    </group>
</vector>
"""


def adaptive(round_icon: bool) -> str:
    what = "round" if round_icon else "square"
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} The {what} mask takes its own bite out of the same two layers. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def background(colour: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<resources>
    <color name="ic_launcher_background">{colour}</color>
</resources>
"""


def write(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    before = path.read_text(encoding="utf-8") if path.exists() else None
    path.write_text(text, encoding="utf-8", newline="\n")
    return before != text


def main() -> int:
    if not LOGO.exists() or not TOKENS.exists():
        print(f"the mark or the tokens are missing: {LOGO}, {TOKENS}", file=sys.stderr)
        return 2
    path, stroke = mark()
    green = dark_token("color-operational")
    surface = dark_token("color-bg")
    changed = [
        write(RES / "drawable" / "ic_launcher_foreground.xml", vector(path, stroke, green)),
        write(RES / "drawable" / "ic_launcher_monochrome.xml", vector(path, stroke, "#FFFFFFFF")),
        write(RES / "values" / "ic_launcher.xml", background(surface)),
        write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", adaptive(False)),
        write(RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml", adaptive(True)),
    ]
    print(f"android icon: the mark {path!r} in {green} on {surface}"
          f" → {RES.relative_to(ROOT).as_posix()} ({'updated' if any(changed) else 'unchanged'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
