"""Turn the `android.*` keys of the shared dictionaries into Android string resources.

`i18n/en.json` and `i18n/ru.json` are the single source of every word the product says. The probe
takes its own slice of them: `values/strings.xml` (English, the fallback Android uses for any
other language) and `values-ru/strings.xml`. Keys become resource names — `android.bind.title`
→ `android_bind_title` — and `{name}` placeholders become positional `%1$s` arguments, numbered by
their first appearance in the English text so both languages pass the same arguments.

Run: python scripts/build_android_strings.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
I18N = ROOT / "i18n"
RES = ROOT / "android" / "app" / "src" / "main" / "res"
PREFIX = "android."
# words the probe needs that do not live under android.*: the shell and a few shared verbs
EXTRA = ("action.back", "action.retry", "app.lang.other", "app.lang.switch", "duration.minute", "duration.hour")
PLACEHOLDER = re.compile(r"\{([a-z_][a-z0-9_]*)\}", re.IGNORECASE)


def resource_name(key: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", key.lower()).strip("_")


def escape(text: str) -> str:
    """Android string escaping: entities, quotes, and a leading @ or ? that would be read as a reference."""
    out = (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
           .replace("'", "\\'").replace('"', "\\\"").replace("\n", "\\n"))
    return "\\" + out if out[:1] in ("@", "?") else out


def positional(text: str, order: list[str]) -> str:
    """{name} -> %1$s using the order worked out from the English text; %% for a literal percent."""
    out = text.replace("%", "%%")
    for index, name in enumerate(order, start=1):
        out = out.replace("{" + name + "}", f"%{index}$s")
    return out


def collect(dictionary: dict) -> list[str]:
    return sorted(k for k in dictionary if k.startswith(PREFIX) or k in EXTRA)


def strings_xml(keys: list[str], dictionary: dict, orders: dict[str, list[str]], lang: str) -> str:
    lines = [
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>",
        f"<!-- Generated by scripts/build_android_strings.py from i18n/{lang}.json. Do not edit. -->",
        "<resources>",
    ]
    for key in keys:
        value = dictionary[key]
        order = orders[key]
        used = set(PLACEHOLDER.findall(value))
        if used - set(order):
            raise SystemExit(f"build_android_strings: {lang}: {key} uses {sorted(used - set(order))}, which the English text does not")
        text = escape(positional(value, order))
        formatted = "" if order else ' formatted="false"'
        lines.append(f'    <string name="{resource_name(key)}"{formatted}>{text}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    before = path.read_text(encoding="utf-8") if path.exists() else None
    path.write_text(text, encoding="utf-8", newline="\n")
    return before != text


def main() -> int:
    try:
        en = json.loads((I18N / "en.json").read_text(encoding="utf-8"))
        ru = json.loads((I18N / "ru.json").read_text(encoding="utf-8"))
    except OSError as error:
        print(f"dictionaries not readable: {error}", file=sys.stderr)
        return 2
    keys = collect(en)
    missing = [k for k in keys if k not in ru]
    extra = [k for k in collect(ru) if k not in keys]
    if missing or extra:
        print(f"dictionaries disagree: only in en {missing}, only in ru {extra}", file=sys.stderr)
        return 1
    orders = {key: list(dict.fromkeys(PLACEHOLDER.findall(en[key]))) for key in keys}
    changed = [
        write(RES / "values" / "strings.xml", strings_xml(keys, en, orders, "en")),
        write(RES / "values-ru" / "strings.xml", strings_xml(keys, ru, orders, "ru")),
    ]
    print(f"android strings: {len(keys)} keys × ru/en → {RES.relative_to(ROOT).as_posix()}"
          f" ({'updated' if any(changed) else 'unchanged'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
